# ----------------------------------------------------------------------
# Table quantisation and FD noise budget
# ----------------------------------------------------------------------
# G is stored to 1 J/mol where |G| >= 1e5 and to 0.01 J/mol elsewhere (asserted on the data in
# check_quantisation).  A value rounded to quantum q carries error ~ U(-q/2, q/2), variance q^2/12.
# Every reference below is a linear functional  ref = sum_k w_k G[row_k]  of table values, so its
# rounding noise is  sigma = sqrt(sum_k (w_k q_k)^2 / 12)  with q_k the quantum of each value in THAT stencil.
Q_BIG, Q_SMALL, BIG_ABS = 1.0, 0.01, 1e5
FLAG_RATIO = 0.25  # noise (or truncation) >= 25% of the estimator MAE -> flagged
MC_DRAWS = 64  # rounding draws per stencil for the expected |noise| (mean absolute value)
SPLINE_DRAWS = 24  # perturbed refits per composition for the spline reference's noise floor
MAX_MT = 5  # widest half-width along T, in grid steps (as in run_second_order_reconciliation)
MAX_MC = 3  # widest half-width along a composition axis (lines have only 11-26 points)
MIN_COMMON_SHARE = 0.3  # ladder cap: the common centre set must keep >= 30% of the narrow-FD points
HEADLINE_EST = "poly"
NOISE_COLS = ["noise_rms", "noise_mae_expected", "noise_over_mae", "noise_mae_over_mae", "noise_over_typical",
              "noise_sq_share", "implied_model_rms", "implied_model_over_typical", "rms_error_over_typical"]


def quantum(g):
    return np.where(np.abs(g) >= BIG_ABS, Q_BIG, Q_SMALL)


def check_quantisation(G):
    big = np.abs(G) >= BIG_ABS
    assert np.allclose(G[big], np.round(G[big], 0)), "|G| >= 1e5 rows are not integer-valued"
    assert np.allclose(G[~big] * 100, np.round(G[~big] * 100)), "|G| < 1e5 rows are not multiples of 0.01"
    return float(big.mean())


@dataclass
class Stencil:
    """sum_k w[:, k] * G[rows[:, k]] for every centre row (centres are unique)."""
    centre: np.ndarray  # (n,) table row of the query point
    rows: np.ndarray  # (n, k) table rows entering the stencil
    w: np.ndarray  # (n, k) weights
    h: np.ndarray  # (n,) half-span along the first axis (T for T-lines, c for c-lines / planes)
    h2: np.ndarray | None = None  # (n,) half-span along T (mixed stencils only)

    def apply(self, v):
        return (self.w * v[self.rows]).sum(axis=1)

    def sigma(self, G):
        """Rounding-noise std of the stencil value, using the quantum of each value actually used."""
        return np.sqrt(((self.w * quantum(G[self.rows])) ** 2).sum(axis=1) / 12.0)

    def noise_mae(self, G, draws=MC_DRAWS, seed=0):
        """E|noise| per stencil by Monte Carlo over uniform rounding errors (deterministic)."""
        u = np.random.default_rng(seed).random((len(self.centre), draws, self.rows.shape[1])) - 0.5
        wq = self.w * quantum(G[self.rows])
        return np.abs((u * wq[:, None, :]).sum(axis=2)).mean(axis=1)

    def restrict(self, centres):
        o = np.argsort(self.centre)
        k = o[np.searchsorted(self.centre[o], centres)]
        assert (self.centre[k] == centres).all()
        return Stencil(self.centre[k], self.rows[k], self.w[k], self.h[k], None if self.h2 is None else self.h2[k])


def line_stencil(lines, order, m):
    """Central stencil of half-width m (in index steps) along each (x, rows) line; order 1 or 2.

    Valid where x[i+m] - x[i] == x[i] - x[i-m] (symmetric about the centre, intermediate nodes may be uneven).
    m = 1 is the narrow stencil of the original sweep.
    """
    cen, rows, w, hh = [], [], [], []
    for x, ridx in lines:
        n = len(x)
        if n < 2 * m + 1:
            continue
        i = np.arange(m, n - m)
        h1, h2 = x[i] - x[i - m], x[i + m] - x[i]
        ok = np.isclose(h1, h2, rtol=STEP_RTOL, atol=STEP_ATOL) & (h1 > 0)
        i, h1, h2 = i[ok], h1[ok], h2[ok]
        if order == 1:
            d = h1 + h2
            rows.append(np.stack([ridx[i - m], ridx[i + m]], 1))
            w.append(np.stack([-1 / d, 1 / d], 1))
        else:
            rows.append(np.stack([ridx[i - m], ridx[i], ridx[i + m]], 1))
            w.append(np.stack([2 / ((h1 + h2) * h1), -2 / (h1 * h2), 2 / ((h1 + h2) * h2)], 1))
        cen.append(ridx[i])
        hh.append(h2)
    return Stencil(np.concatenate(cen), np.concatenate(rows), np.concatenate(w), np.concatenate(hh))


def plane_stencil(cs, Ts, R, mc, mt):
    """Central 4-corner mixed stencil with half-widths mc (c) and mt (T), symmetric about the centre."""
    def sym(x, m):
        i = np.arange(m, len(x) - m)
        ok = np.isclose(x[i] - x[i - m], x[i + m] - x[i], rtol=STEP_RTOL, atol=STEP_ATOL) & (x[i] > x[i - m])
        return i[ok]
    ii, jj = np.meshgrid(sym(cs, mc), sym(Ts, mt), indexing="ij")
    ii, jj = ii.ravel(), jj.ravel()
    rows = np.stack([R[ii + mc, jj + mt], R[ii + mc, jj - mt], R[ii - mc, jj + mt], R[ii - mc, jj - mt]], 1)
    keep = (rows.min(axis=1) >= 0) & (R[ii, jj] >= 0)
    ii, jj, rows = ii[keep], jj[keep], rows[keep]
    hc, ht = cs[ii + mc] - cs[ii], Ts[jj + mt] - Ts[jj]
    den = (cs[ii + mc] - cs[ii - mc]) * (Ts[jj + mt] - Ts[jj - mt])
    w = np.stack([1 / den, -1 / den, -1 / den, 1 / den], 1)
    return Stencil(R[ii, jj], rows, w, hc, ht)


def axis_lines(df, comp_cols, base, axis):
    """(x sorted, table rows) of every FD line along `axis` ('T': one per composition; element: one per T on its sweep)."""
    if axis == "T":
        groups, key = df.groupby(comp_cols, sort=False), TEMP_COL
    else:
        others = [c for c in comp_cols if c != col(axis)]
        on = np.all(np.isclose(df[others].to_numpy(), base[others].to_numpy()), axis=1)
        groups, key = df[on].groupby(TEMP_COL, sort=False), col(axis)
    out = []
    for _, grp in groups:
        grp = grp.sort_values(key)
        if len(grp) >= 3:
            out.append((grp[key].to_numpy(float), grp.index.to_numpy()))
    return out


def plane_grid(df, comp_cols, base, el):
    """(c values, T values, R) with R[ci, ti] = table row of element el's (c, T) plane (-1 where absent)."""
    others = [c for c in comp_cols if c != col(el)]
    line = df[np.all(np.isclose(df[others].to_numpy(), base[others].to_numpy()), axis=1)]
    cs, Ts = np.sort(line[col(el)].unique()), np.sort(line[TEMP_COL].unique())
    ci = np.searchsorted(cs, line[col(el)].to_numpy())
    ti = np.searchsorted(Ts, line[TEMP_COL].to_numpy())
    R = -np.ones((len(cs), len(Ts)), dtype=np.int64)
    R[ci, ti] = line.index.to_numpy()
    assert (np.bincount(ci * len(Ts) + ti, minlength=R.size) <= 1).all(), "duplicate (c,T) on line"
    return cs, Ts, R


@dataclass
class Ref:
    """A finite reference at the common centre rows, with its own rounding-noise floor."""
    name: str
    centre: np.ndarray
    val: np.ndarray
    sigma: np.ndarray  # noise std of the reference value
    noise_mae: np.ndarray  # E|noise|
    stencil: Stencil | None = None
    m_c: float = np.nan  # half-width in grid steps (c axis, or the only axis for 1-D lines)
    m_t: float = np.nan  # half-width along T (mixed stencils)

    @classmethod
    def from_stencil(cls, name, st, G, m_c, m_t=np.nan):
        return cls(name, st.centre, st.apply(G), st.sigma(G), st.noise_mae(G), st, m_c, m_t)


def build_ladder(G, kind, src, max_m, max_mt=MAX_MT, min_share=MIN_COMMON_SHARE):
    """Narrow and wide FD references of one quantity.

    kind 'd1' / 'd2': src = lines, ladder half-widths m = 1..M with M <= max_m.
    kind 'mixed':     src = (cs, Ts, R), ladder (mc, mt) in [1..Mc] x [1..max_mt], Mc <= max_m.
    Returns (narrow_all: Ref on every narrow-eligible point,
             ladder: {label: Ref} on the COMMON centre set C valid for every ladder entry ('narrow' = m 1),
             info).  M (Mc for mixed) is the widest cap for which |C| >= min_share * |narrow-eligible|.
    """
    if kind == "mixed":
        cs, Ts, R = src
        make = lambda a: plane_stencil(cs, Ts, R, a[0], a[1])  # noqa: E731
        keys = lambda M: [(a, b) for a in range(1, M + 1) for b in range(1, max_mt + 1)]  # noqa: E731
        top = max_m
    else:
        order = 1 if kind == "d1" else 2
        make = lambda a: line_stencil(src, order, a)  # noqa: E731
        keys = lambda M: list(range(1, M + 1))  # noqa: E731
        top = max_m
    base_key = (1, 1) if kind == "mixed" else 1
    narrow = make(base_key)
    cache = {}
    for M in range(top, 0, -1):
        for k in keys(M):
            cache.setdefault(k, make(k))
        common = np.sort(narrow.centre)
        for k in keys(M):
            common = np.intersect1d(common, cache[k].centre)
        if len(common) >= min_share * len(narrow.centre) or M == 1:
            break
    ladder = {}
    for k in keys(M):
        mc, mt = (k if kind == "mixed" else (k, np.nan))
        label = "narrow" if k == base_key else (f"wide_c{mc}_T{mt}" if kind == "mixed" else f"wide_m{k}")
        ladder[label] = Ref.from_stencil(label, cache[k].restrict(common), G, mc, mt)
    narrow_all = Ref.from_stencil("narrow_all", narrow, G, 1, 1 if kind == "mixed" else np.nan)
    info = {"n_narrow": int(len(narrow.centre)), "n_common": int(len(common)), "cap": int(M),
            "steps": sorted(set(np.round(narrow.h, 6).tolist()))}
    return narrow_all, ladder, info


def spline_T_reference(df, comp_cols, draws=SPLINE_DRAWS, seed=0):
    """Smoothing-spline dG/dT and d2G/dT2 per composition line (the Newton-test truth) and its noise floor.

    Spline = PPolyEval.smooth_truth of run_newton_test (degree-4 UnivariateSpline, s = N * 0.3^2).
    Noise floor = std over `draws` refits of the table perturbed by fresh uniform rounding errors of the
    per-value quantum (knot selection included).  Returns arrays over table rows: S1, S2, N1, N2.
    """
    from run_newton_test import PPolyEval  # lazy: heavy import
    G = df[DEFAULT_TARGET].to_numpy(float)
    Tall = df[TEMP_COL].to_numpy(float)
    rng = np.random.default_rng(seed)
    S1, S2, N1, N2 = (np.full(len(df), np.nan) for _ in range(4))

    def derivs(T, g):
        ev, _ = PPolyEval.smooth_truth(T, g)
        v = np.array([ev.gtt(t) for t in T])
        return v[:, 1], v[:, 2]

    for _, grp in df.groupby(comp_cols, sort=False):
        grp = grp.sort_values(TEMP_COL)
        r, T, g = grp.index.to_numpy(), Tall[grp.index], G[grp.index]
        S1[r], S2[r] = derivs(T, g)
        d1, d2 = [], []
        for _ in range(draws):
            a, b = derivs(T, g + (rng.random(len(g)) - 0.5) * quantum(g))
            d1.append(a)
            d2.append(b)
        N1[r], N2[r] = np.std(d1, axis=0, ddof=1), np.std(d2, axis=0, ddof=1)
    return S1, S2, N1, N2


def spline_ref(centre, val, sigma):
    return Ref("spline", centre, val[centre], sigma[centre], np.sqrt(2 / np.pi) * sigma[centre])  # E|N| for Gaussian noise


def ref_metrics(ref, est, poly, G_poly, mask, narrow_val):
    """Estimator-vs-reference metrics on `mask`, plus the reference's noise budget (all arrays aligned with ref.centre).

    est: estimator values; poly: analytic polynomial value of the same quantity (for the truncation proxy);
    narrow_val: the narrow-FD reference at the same centres.
    """
    fd, e = ref.val[mask], est[mask]
    out = metrics(fd, e)
    mse = float(np.mean((e - fd) ** 2))
    nr = float(np.sqrt(np.mean(ref.sigma[mask] ** 2)))
    nm = float(np.mean(ref.noise_mae[mask]))
    out.update({
        "noise_rms": nr, "noise_mae_expected": nm,
        "noise_over_mae": nr / out["mae"], "noise_mae_over_mae": nm / out["mae"],
        "noise_over_typical": nr / out["typical_abs"],
        "rms_error_over_typical": float(np.sqrt(mse) / out["typical_abs"]),
        "noise_sq_share": nr ** 2 / mse,  # share of the mean squared error (quadrature, noise independent of model error)
        "implied_model_rms": float(np.sqrt(max(mse - nr ** 2, 0.0))),
        "implied_model_over_typical": float(np.sqrt(max(mse - nr ** 2, 0.0)) / out["typical_abs"]),
        "trunc_mae": (float(np.mean(np.abs(poly[mask] - ref.stencil.apply(G_poly)[mask]))) if ref.stencil is not None else np.nan),
        "ref_vs_narrow_mae": float(np.mean(np.abs(fd - narrow_val[mask]))),
    })
    return out


def ref_rows(base, ladder, spline, ests, in_fit):
    """Long-format rows: every estimator x subset x reference (ladder entries, plus the spline if given)."""
    refs = dict(ladder)
    if spline is not None:
        refs["spline"] = spline
    narrow = ladder["narrow"]
    out = []
    for subset, mask in (("all_grid", np.ones(len(narrow.centre), bool)), ("test_only", ~in_fit[narrow.centre])):
        if not mask.any():
            continue
        for est, e in ests["values"].items():
            for name, ref in refs.items():
                out.append({**base, "subset": subset, "estimator": est, "ref": name, "m_c": ref.m_c, "m_t": ref.m_t,
                            "n_common": len(narrow.centre),
                            **ref_metrics(ref, e, ests["values"]["poly"], ests["G_poly"], mask, narrow.val)})
    return out


def summarise_refs(refs, key, order, ddof):
    """Seed mean/std of every numeric column of the long-format reference rows, per (key, subset, estimator, ref)."""
    cols = ["n", "mae", "typical_abs", "normalized_error", "pearson", *NOISE_COLS, "trunc_mae", "ref_vs_narrow_mae"]
    g = refs.groupby([key, "subset", "estimator", "ref"], sort=False)
    out = g[cols].mean().add_suffix("_mean").join(g[cols].std(ddof=ddof).add_suffix("_std"))
    out = out.join(g[["m_c", "m_t", "n_common"]].first())
    out["n_seeds"] = g.size()
    out = out.reset_index()
    out["trunc_over_mae"] = out.trunc_mae_mean / out.mae_mean
    out["flag_noise_limited"] = out.noise_over_mae_mean >= FLAG_RATIO
    out["_o"] = out[key].map({k: i for i, k in enumerate(order)})
    return out.sort_values(["subset", "estimator", "_o"], kind="stable").drop(columns="_o").reset_index(drop=True)


def pick_headline(ref_summ, key):
    """Wide reference per quantity: the ladder entry (not the narrow one) with the smallest predicted FD error budget
    sqrt(noise_rms^2 + trunc_mae^2) (seed-mean, poly, all grid points).  Noise is the exact per-stencil rounding rms;
    trunc is the stencil applied to the polynomial's own values vs its analytic derivative (a proxy).  The choice never
    looks at the polynomial-vs-FD error."""
    out = {}
    S = ref_summ[(ref_summ.subset == "all_grid") & (ref_summ.estimator == HEADLINE_EST)]
    for k, g in S.groupby(key, sort=False):
        lad = g[g.ref.str.startswith("wide")]
        out[k] = None if lad.empty else lad.loc[np.hypot(lad.noise_rms_mean, lad.trunc_mae_mean).idxmin(), "ref"]
    return out


NOISE_DOMINATES = 0.5  # noise share of the squared P-vs-FD error at/above which the error is called FD noise


def attribution(srow, refs_g, head):
    """Model error or FD noise?  One quantity, from seed-mean summary rows (all grid, poly estimator).

    srow    row of the main summary: polynomial vs the narrow FD on every eligible point (noise budget included)
    refs_g  rows of the refs summary for the same quantity (narrow / wide ladder / spline on the common set)
    head    label of the headline wide reference (or None)

    Rule on the narrow-FD budget, from the exact per-stencil rounding noise and independent of any fit to it:
      noise_sq_share = noise_rms^2 / mean((P - FD)^2)
      >= NOISE_DOMINATES   -> 'FD noise'
      <  FLAG_RATIO        -> 'model error'
      otherwise            -> 'mixed'
    Cross-check: if the error is mostly noise, averaging the noise down (wide FD / spline) must shrink it.  The change
    to the best second reference is reported with the gap between that reference and the narrow FD in units of the
    narrow FD's expected |noise|: a change that comes with a gap much larger than the noise is stencil truncation /
    smoothing, not rounding noise.
    """
    R = refs_g.set_index("ref")
    wide = R[R.index.str.startswith("wide")]
    share = float(srow.noise_sq_share_mean)
    out = {
        "nerr_narrow": float(srow.normalized_error_mean), "mae": float(srow.mae_mean), "typical_abs": float(srow.typical_abs_mean),
        "noise_rms": float(srow.noise_rms_mean), "noise_over_typical": float(srow.noise_over_typical_mean),
        "noise_over_mae": float(srow.noise_over_mae_mean), "noise_sq_share": share,
        "implied_model_over_typical": float(srow.implied_model_over_typical_mean),
        "rms_over_typical": float(srow.rms_error_over_typical_mean),
        "trunc_over_mae": float(srow.trunc_over_mae),
        "n_common": int(R.loc["narrow", "n_mean"]), "nerr_narrow_common": float(R.loc["narrow", "normalized_error_mean"]),
        "head": head, "nerr_wide": np.nan, "wide_noise_over_typical": np.nan, "wide_trunc_over_typical": np.nan,
        "ladder_min": np.nan, "ladder_max": np.nan, "nerr_spline": np.nan, "spline_noise_over_typical": np.nan,
    }
    if len(wide):
        out["ladder_min"], out["ladder_max"] = float(wide.normalized_error_mean.min()), float(wide.normalized_error_mean.max())
    if head is not None:
        w = R.loc[head]
        out.update(nerr_wide=float(w.normalized_error_mean), wide_noise_over_typical=float(w.noise_over_typical_mean),
                   wide_trunc_over_typical=float(w.trunc_mae_mean / w.typical_abs_mean))
    if "spline" in R.index:
        out.update(nerr_spline=float(R.loc["spline", "normalized_error_mean"]),
                   spline_noise_over_typical=float(R.loc["spline", "noise_over_typical_mean"]))
    out["verdict"] = ("FD noise" if share >= NOISE_DOMINATES else "model error" if share < FLAG_RATIO else "mixed")
    out.update(best_second_ref=np.nan, best_second_label=None, second_ref_change=np.nan, gap_over_noise=np.nan,
               narrow_noise_mae_common=float(R.loc["narrow", "noise_mae_expected_mean"]))
    cand = R[(R.index.str.startswith("wide")) | (R.index == "spline")]
    if len(cand):
        bl = cand.normalized_error_mean.idxmin()
        out.update(best_second_ref=float(cand.loc[bl, "normalized_error_mean"]), best_second_label=bl,
                   second_ref_change=float(cand.loc[bl, "normalized_error_mean"] / out["nerr_narrow_common"] - 1.0),
                   gap_over_noise=float(cand.loc[bl, "ref_vs_narrow_mae_mean"] / out["narrow_noise_mae_common"]))
    return out



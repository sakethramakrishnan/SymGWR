    comp_cols = [c for c in feats if c != TEMP_COL]
    t_idx = feats.index(TEMP_COL)
    fidx = {"T": t_idx, **{el: feats.index(col(el)) for el in ELEMENTS}}
    base = df[comp_cols].mode().iloc[0]
    G = df[DEFAULT_TARGET].to_numpy(float)
    share_big = check_quantisation(G)
    axes = ["T"] + ELEMENTS
    n_comp, n_T = df.groupby(comp_cols).ngroups, df[TEMP_COL].nunique()

    # ---- references (seed independent): narrow FD on every eligible point, ladder of wide FD on the common set ----
    narrow_all, ladders, infos = {}, {}, {}
    for axis in axes:
        narrow_all[axis], ladders[axis], infos[axis] = build_ladder(
            G, "d1", axis_lines(df, comp_cols, base, axis), args.max_mt if axis == "T" else args.max_mc, args.max_mt)
    for el in ELEMENTS:
        infos[el]["n_nodes"] = int(df[col(el)][np.all(np.isclose(df[[c for c in comp_cols if c != col(el)]].to_numpy(),
                                                              base[[c for c in comp_cols if c != col(el)]].to_numpy()), axis=1)].nunique())
    print(f"rows={len(df)}  compositions={n_comp}  quantised: {share_big:.1%} of G on the 1 J/mol quantum")
    print("FD-eligible points per axis:", {a: infos[a]["n_narrow"] for a in axes})
    print(f"dG/dT expected n = {n_comp} x {n_T - 2} = {n_comp * (n_T - 2)}; got {infos['T']['n_narrow']}")
    print("ladder:", {a: (infos[a]["cap"], infos[a]["n_common"]) for a in axes}, "(cap, |common set|)")
    S1, _, N1, _ = spline_T_reference(df, comp_cols)
    spline = spline_ref(ladders["T"]["narrow"].centre, S1, N1)

    X_raw_all = df[feats].to_numpy(float)
    rows, ref_out, ident_rows = [], [], []
    grad_store = {a: [] for a in axes}  # raw-unit poly gradient at all-grid FD points, per seed

    for seed in args.seeds:
        t0 = time.time()
        sp = get_split("random", seed, data_path=args.data, verbose=False)
        fit_idx = np.concatenate([sp.train_idx, sp.val_idx])
        X_fit = np.vstack([sp.X_train, sp.X_val])
        y_fit = np.concatenate([sp.y_train, sp.y_val])
        model, _ = fit_polynomial_regression(X_fit, y_fit, degree=args.degree)
        poly = model.named_steps["poly_features"]

        # scaled-space gradient at every row -> raw units
        X_all = sp.feature_scaler.transform(X_raw_all)
        g_scaled = evaluate_polynomial_pipeline_gradients(model, X_all)
        t_scale = float(sp.target_scaler.scale_[0])
        f_scale = np.asarray(sp.feature_scaler.scale_)
        g_raw = g_scaled * (t_scale / f_scale)[None, :]

        # GWR k=1: gradient at nearest fit reference point (scaled space)
        tree = cKDTree(X_fit)
        _, nn = tree.query(X_all, k=1)
        g_raw_k1 = g_raw[fit_idx[nn]]

        # model values (raw) for the stencil-truncation diagnostic
        G_poly = sp.target_scaler.inverse_transform(model.predict(X_all).reshape(-1, 1)).ravel()

        # design null space (centred, bias-free = what min-norm solve sees)
        Phi = poly.transform(X_fit)[:, 1:]
        Phi = Phi - Phi.mean(axis=0)
        s = np.linalg.svd(Phi, compute_uv=False)
        tol = s.max() * max(Phi.shape) * np.finfo(Phi.dtype).eps
        rank = int((s > tol).sum())
        _, _, Vh = np.linalg.svd(Phi, full_matrices=False)
        Vr = Vh[:rank]
        powers = poly.powers_[1:]

        in_fit = np.zeros(len(df), bool)
        in_fit[fit_idx] = True

        for axis in axes:
            j = fidx[axis]
            na = narrow_all[axis]
            r = na.centre
            est_all = {"poly": g_raw[:, j], "gwr_k1": g_raw_k1[:, j]}
            grad_store[axis].append(pd.Series(g_raw[r, j], index=r))
            stencil_val = na.stencil.apply(G_poly)

            # null fraction of d/d(axis) at these points (scaled space, in-plane)
            nf = null_frac(deriv_matrix(powers, X_all[r], {j: 1}), Vr)

            for subset, mask in (("all_grid", np.ones(len(r), bool)), ("test_only", ~in_fit[r])):
                for est, e in est_all.items():
                    m = ref_metrics(na, e[r], est_all["poly"][r], G_poly, mask, na.val)
                    m["stencil_trunc_mae"] = m.pop("trunc_mae")
                    m.pop("ref_vs_narrow_mae")
                    rows.append({
                        "seed": seed, "axis": axis, "subset": subset, "estimator": est, **m,
                        "fd_vs_polystencil_mae": float(np.mean(np.abs(stencil_val[mask] - na.val[mask]))),
                        "null_frac_mean": float(np.nanmean(nf[mask])) if est == "poly" else np.nan,
                        "fit_rank": rank, "n_fit_rows": len(fit_idx),
                    })

            C = ladders[axis]["narrow"].centre
            ref_out += ref_rows({"seed": seed, "axis": axis}, ladders[axis], spline if axis == "T" else None,
                                {"values": {k: v[C] for k, v in est_all.items()}, "G_poly": G_poly}, in_fit)

        # ---- identifiability table (poly, all FD points of the plane) ----
        def add(label, order, where, J):
            nf = null_frac(J, Vr)
            ident_rows.append({
                "seed": seed, "derivative": label, "order": order, "evaluated_at": where,
                "n_points": int(len(J)), "null_frac_mean": float(np.nanmean(nf)),
                "null_frac_max": float(np.nanmax(nf)), "fit_rank": rank,
                "n_terms": int(Phi.shape[1]), "sv_rank_th": float(s[rank - 1]),
                "sv_next": float(s[rank]) if rank < len(s) else np.nan,
            })

        ni = feats.index(col("Ni"))
        for el in ELEMENTS:
            plane_rows = np.unique(narrow_all[el].centre)
            Xp = X_all[plane_rows]
            off_base = np.abs(X_raw_all[plane_rows, fidx[el]] - base[col(el)]) > 1e-9
            je, jt = fidx[el], t_idx
            add(f"d/d{el}", 1, f"{el}-plane", deriv_matrix(powers, Xp, {je: 1}))
            add(f"d/dT", 1, f"{el}-plane", deriv_matrix(powers, Xp, {jt: 1}))
            add(f"d2/d{el}2", 2, f"{el}-plane", deriv_matrix(powers, Xp, {je: 2}))
            add(f"d2/d{el}dT", 2, f"{el}-plane", deriv_matrix(powers, Xp, {je: 1, jt: 1}))
            add("d/dNi", 1, f"{el}-plane", deriv_matrix(powers, Xp, {ni: 1}))
            for other in ELEMENTS:
                if other == el:
                    continue
                jo = fidx[other]
                add(f"d/d{other}", 1, f"{el}-plane, {el}!=base", deriv_matrix(powers, Xp[off_base], {jo: 1}))
                add(f"d2/d{el}d{other}", 2, f"{el}-plane, {el}!=base",
                    deriv_matrix(powers, Xp[off_base], {je: 1, jo: 1}))

        print(f"seed {seed}: rank={rank}/{Phi.shape[1]} fit_rows={len(fit_idx)} ({time.time()-t0:.1f}s)", flush=True)

    per_seed = pd.DataFrame(rows)
    per_seed.to_csv(os.path.join(args.out_dir, "derivative_fidelity.csv"), index=False)
    ident = pd.DataFrame(ident_rows)
    ident.to_csv(os.path.join(args.out_dir, "derivative_identifiability.csv"), index=False)

    # ---- cross-seed pointwise spread of the poly gradient (all-grid points) ----
    spread = {}
    for axis in axes:
        Gs = pd.concat(grad_store[axis], axis=1)  # points x seeds (index = row; unique per axis)
        spread[axis] = float(Gs.std(axis=1, ddof=0).mean() / np.mean(np.abs(narrow_all[axis].val)))

    # ---- summary: mean +/- std over seeds ----
    metric_cols = ["n", "mae", "typical_abs", "normalized_error", "pearson",
                   "stencil_trunc_mae", "fd_vs_polystencil_mae", "null_frac_mean", *NOISE_COLS]
    g = per_seed.groupby(["axis", "subset", "estimator"], sort=False)
    mean, std = g[metric_cols].mean(), g[metric_cols].std(ddof=0)
    summ = mean.add_suffix("_mean").join(std.add_suffix("_std")).reset_index()
    summ["n_seeds"] = g.size().to_numpy()
    summ["grad_seed_std_over_typical"] = summ.apply(
        lambda r: spread[r["axis"]] if (r["subset"] == "all_grid" and r["estimator"] == "poly") else np.nan, axis=1)
    summ["trunc_over_mae"] = summ.stencil_trunc_mae_mean / summ.mae_mean
    summ["flag_noise_limited"] = summ.noise_over_mae_mean >= FLAG_RATIO
    summ["flag_trunc_limited"] = summ.trunc_over_mae >= FLAG_RATIO
    summ["flag_fd_limited"] = summ.flag_noise_limited | summ.flag_trunc_limited
    summ["axis"] = pd.Categorical(summ["axis"], axes, ordered=True)
    summ = summ.sort_values(["subset", "estimator", "axis"]).reset_index(drop=True)
    summ.to_csv(os.path.join(args.out_dir, "derivative_fidelity_summary.csv"), index=False)

    # ---- second reference (wide FD ladder on the common set; smoothing spline for T) ----
    refs = pd.DataFrame(ref_out)
    refs.to_csv(os.path.join(args.out_dir, "derivative_fidelity_refs.csv"), index=False)
    refs_summ = summarise_refs(refs, "axis", axes, ddof=0)
    head = pick_headline(refs_summ, "axis")
    refs_summ["headline"] = [head.get(a) == r for a, r in zip(refs_summ["axis"], refs_summ["ref"])]
    refs_summ.to_csv(os.path.join(args.out_dir, "derivative_fidelity_refs_summary.csv"), index=False)

    ctx = {"n_comp": n_comp, "n_T": n_T, "n_rows": len(df), "share_big": share_big, "seeds": args.seeds,
           "infos": infos, "headline": head, "ident": ident, "per_seed": per_seed, "spread": spread,
           "base": {el: float(base[col(el)]) for el in ELEMENTS},
           "n_fit_rows": int(per_seed.n_fit_rows.iloc[0]), "degree": args.degree}
    write_markdown(args.out_dir, summ, refs_summ, ctx)
    print(summ[["axis", "subset", "estimator", "n_mean", "mae_mean", "typical_abs_mean", "normalized_error_mean",
                "noise_rms_mean", "noise_over_mae_mean", "noise_over_typical_mean", "noise_sq_share_mean"]]
          .to_string(float_format=lambda v: f"{v:.4g}"))


